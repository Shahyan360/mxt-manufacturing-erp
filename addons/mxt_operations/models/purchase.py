from odoo import api, fields, models, _
from odoo.exceptions import AccessError, UserError, ValidationError


class Company(models.Model):
    _inherit = 'res.company'

    mxt_final_threshold = fields.Monetary(
        string='Lab Final Approval Threshold', default=1000,
        help='Proposed rule, in company currency. Every PO requires manager review; '
             'amounts above this value also require a different final approver.')

    @api.constrains('mxt_final_threshold')
    def _check_mxt_threshold(self):
        if any(c.mxt_final_threshold < 0 for c in self):
            raise ValidationError(_('Approval threshold cannot be negative.'))

    def write(self, vals):
        if 'mxt_final_threshold' in vals and not self.env.user.has_group('base.group_system'):
            raise AccessError(_('Only settings administrators may change approval policy.'))
        return super().write(vals)


class ApprovalEvent(models.Model):
    _name = 'mxt.approval.event'
    _description = 'Immutable Purchase Approval Event'
    _order = 'id desc'
    _check_company_auto = True

    order_id = fields.Many2one('purchase.order', required=True, ondelete='cascade', check_company=True)
    company_id = fields.Many2one(related='order_id.company_id', store=True, index=True)
    actor_id = fields.Many2one('res.users', required=True)
    action = fields.Char(required=True)
    note = fields.Text()
    occurred_at = fields.Datetime(required=True, default=fields.Datetime.now)

    @api.model_create_multi
    def create(self, vals_list):
        if not self.env.su:
            raise AccessError(_('Approval history is generated by workflow actions.'))
        return super().create(vals_list)

    def write(self, vals):
        raise AccessError(_('Approval history is immutable.'))

    def unlink(self):
        raise AccessError(_('Approval history is immutable.'))


class PurchaseOrder(models.Model):
    _inherit = 'purchase.order'

    mxt_approval_state = fields.Selection([
        ('draft', 'Draft'), ('submitted', 'Submitted'),
        ('manager', 'Manager Approved'), ('approved', 'Final Approved'),
        ('rejected', 'Rejected'),
    ], default='draft', copy=False, readonly=True, tracking=True)
    mxt_requester_id = fields.Many2one('res.users', readonly=True, copy=False)
    mxt_manager_id = fields.Many2one('res.users', readonly=True, copy=False)
    mxt_final_id = fields.Many2one('res.users', readonly=True, copy=False)
    mxt_rejection_reason = fields.Text()
    mxt_event_ids = fields.One2many('mxt.approval.event', 'order_id', readonly=True)
    mxt_needs_final = fields.Boolean(compute='_compute_mxt_needs_final')

    @api.depends('amount_total', 'currency_id', 'company_id.mxt_final_threshold', 'date_order')
    def _compute_mxt_needs_final(self):
        for order in self:
            amount = order.currency_id._convert(
                order.amount_total, order.company_id.currency_id, order.company_id,
                fields.Date.to_date(order.date_order) or fields.Date.context_today(order))
            order.mxt_needs_final = amount > order.company_id.mxt_final_threshold

    def _mxt_check_access(self):
        self.check_access_rights('write')
        self.check_access_rule('write')
        if any(o.company_id not in self.env.companies for o in self):
            raise AccessError(_('Company is outside the allowed context.'))
        if self:
            self.env.cr.execute('SELECT id FROM purchase_order WHERE id IN %s ORDER BY id FOR UPDATE',
                                (tuple(self.ids),))
            self.invalidate_recordset(['mxt_approval_state', 'mxt_requester_id',
                                       'mxt_manager_id', 'mxt_final_id'])

    def _mxt_event(self, action, note=''):
        self.ensure_one()
        # Narrow elevation: append a server-authored event only after order access
        # and role checks. No user-supplied actor or company is accepted.
        self.env['mxt.approval.event'].sudo().create({
            'order_id': self.id, 'actor_id': self.env.uid,
            'action': action, 'note': note,
        })
        self.message_post(body=_('Purchase approval: %s') % action)

    @api.model_create_multi
    def create(self, vals_list):
        protected = {'mxt_requester_id', 'mxt_manager_id', 'mxt_final_id', 'mxt_event_ids'}
        for vals in vals_list:
            if protected.intersection(vals) or vals.get('mxt_approval_state', 'draft') != 'draft':
                raise AccessError(_('Use purchase approval actions.'))
            if vals.get('state', 'draft') not in ('draft', 'sent'):
                raise AccessError(_('Create an RFQ before confirming a purchase.'))
        return super().create(vals_list)

    def write(self, vals):
        if {'mxt_approval_state', 'mxt_requester_id', 'mxt_manager_id',
            'mxt_final_id', 'mxt_event_ids'}.intersection(vals):
            raise AccessError(_('Use purchase approval actions.'))
        if {'partner_id', 'currency_id', 'company_id', 'order_line',
            'date_order', 'picking_type_id'}.intersection(vals):
            if any(o.mxt_approval_state not in ('draft', 'rejected') for o in self):
                raise UserError(_('Reset approval before changing reviewed purchase data.'))
        if vals.get('state') in ('purchase', 'done'):
            self._mxt_require_approved()
        return super().write(vals)

    def _mxt_require_approved(self):
        self._mxt_check_access()
        for order in self:
            if order.mxt_approval_state != 'approved' or not order.mxt_manager_id:
                raise UserError(_('Manager and, when required, final approval must precede confirmation.'))
            if order.mxt_needs_final and not order.mxt_final_id:
                raise UserError(_('The current amount requires final approval.'))

    def action_mxt_submit(self):
        self._mxt_check_access()
        for order in self:
            if order.state not in ('draft', 'sent') or order.mxt_approval_state != 'draft':
                raise UserError(_('Only a draft RFQ can be submitted once.'))
            if not order.order_line.filtered(lambda l: not l.display_type):
                raise UserError(_('Add purchase lines first.'))
            super(PurchaseOrder, order).write({
                'mxt_approval_state': 'submitted', 'mxt_requester_id': self.env.uid,
            })
            order._mxt_event('Submitted')
        return True

    def action_mxt_manager_approve(self):
        self._mxt_check_access()
        if not self.env.user.has_group('mxt_operations.group_procurement_manager'):
            raise AccessError(_('A procurement manager must approve.'))
        for order in self:
            if order.mxt_approval_state != 'submitted':
                raise UserError(_('Submit the RFQ before manager approval.'))
            if order.mxt_requester_id == self.env.user:
                raise AccessError(_('The requester cannot approve their own request.'))
            super(PurchaseOrder, order).write({
                'mxt_approval_state': 'manager' if order.mxt_needs_final else 'approved',
                'mxt_manager_id': self.env.uid,
            })
            order._mxt_event('Manager approved')
        return True

    def action_mxt_final_approve(self):
        self._mxt_check_access()
        if not self.env.user.has_group('mxt_operations.group_final_approver'):
            raise AccessError(_('A final approver is required.'))
        for order in self:
            if order.mxt_approval_state != 'manager':
                raise UserError(_('Manager approval must precede final approval.'))
            if self.env.user in (order.mxt_requester_id | order.mxt_manager_id):
                raise AccessError(_('Final approval requires a different person.'))
            super(PurchaseOrder, order).write({
                'mxt_approval_state': 'approved', 'mxt_final_id': self.env.uid,
            })
            order._mxt_event('Final approved')
        return True

    def action_mxt_reject(self):
        self._mxt_check_access()
        if not self.env.user.has_group('mxt_operations.group_procurement_manager'):
            raise AccessError(_('A procurement manager must reject.'))
        for order in self:
            if order.mxt_approval_state not in ('submitted', 'manager') or not order.mxt_rejection_reason:
                raise UserError(_('A pending request and rejection reason are required.'))
            super(PurchaseOrder, order).write({'mxt_approval_state': 'rejected'})
            order._mxt_event('Rejected', order.mxt_rejection_reason)
        return True

    def action_mxt_reset(self):
        self._mxt_check_access()
        for order in self:
            if order.state not in ('draft', 'sent', 'cancel'):
                raise UserError(_('Cancel the native purchase order before resetting approval.'))
            if order.mxt_approval_state == 'draft':
                continue
            if (self.env.user != order.mxt_requester_id
                    and not self.env.user.has_group('mxt_operations.group_procurement_manager')):
                raise AccessError(_('Only the requester or procurement manager may reset.'))
            super(PurchaseOrder, order).write({
                'mxt_approval_state': 'draft', 'mxt_requester_id': False,
                'mxt_manager_id': False, 'mxt_final_id': False,
            })
            order._mxt_event('Reset')
        return True

    def button_confirm(self):
        self._mxt_require_approved()
        return super().button_confirm()

    def button_approve(self, force=False):
        self._mxt_require_approved()
        return super().button_approve(force=force)


class PurchaseOrderLine(models.Model):
    _inherit = 'purchase.order.line'

    def _mxt_check_edit(self):
        self.order_id._mxt_check_access()
        if any(l.order_id.mxt_approval_state not in ('draft', 'rejected') for l in self):
            raise UserError(_('Reset approval before editing reviewed purchase lines.'))

    @api.model_create_multi
    def create(self, vals_list):
        for vals in vals_list:
            order = self.env['purchase.order'].browse(vals.get('order_id'))
            order.check_access_rule('write')
            if order.mxt_approval_state not in ('draft', 'rejected'):
                raise UserError(_('Reset approval before adding purchase lines.'))
        return super().create(vals_list)

    def write(self, vals):
        # Native receipt/billing computations must remain writable.
        if {'product_id', 'product_qty', 'product_uom', 'price_unit', 'taxes_id',
            'order_id', 'discount', 'date_planned', 'name'}.intersection(vals):
            self._mxt_check_edit()
            if vals.get('order_id'):
                target = self.env['purchase.order'].browse(vals['order_id'])
                target.check_access_rule('write')
                if target.mxt_approval_state not in ('draft', 'rejected'):
                    raise UserError(_('Cannot move a line into a reviewed purchase.'))
        return super().write(vals)

    def unlink(self):
        self._mxt_check_edit()
        return super().unlink()
